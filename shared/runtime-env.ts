export function applyRuntimeEnvAliases(env: NodeJS.ProcessEnv): void {
  for (const [canonical, candidates] of Object.entries(aliases)) {
    if (env[canonical]) continue;
    const value = candidates.map((key) => env[key]).find(Boolean);
    if (value) env[canonical] = value;
  }
  // An OAuth client secret is not an HCB API token.
  if (!env.NUXT_HCB_API_TOKEN) {
    const legacy = env.NUXT_HCB_SECRET || env.HCB_SECRET || env.NUXT_HCB_API || env.HCB_API;
    if (legacy?.startsWith("hcb_")) env.NUXT_HCB_API_TOKEN = legacy;
  }
}
